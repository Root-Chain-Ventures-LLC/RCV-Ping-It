#!/usr/bin/env bash
# PingIt installer.
#
# Run it from the directory you extracted the install bundle into:
#     ./install.sh
#
# What this does:
#   1. Checks Docker and the Docker Compose v2 plugin are present.
#   2. Creates `.env` from `.env.example` (pinned to this release) and fills in
#      strong random secrets: database password, Fernet secrets-encryption key,
#      session secrets and the Ed25519 agent-signing keypair.
#   3. Pulls the published images and starts the stack.
#   4. Prints the URL and how to read the one-time first-run setup token.
#
# Safe to re-run: an existing `.env` is never overwritten; only blank secrets
# are filled in. To upgrade, change PINGIT_VERSION in `.env` and run
# `docker compose pull && docker compose up -d` (see the README).

set -euo pipefail

YELLOW=$'\033[33m'; CYAN=$'\033[36m'; GREEN=$'\033[32m'; RED=$'\033[31m'; RESET=$'\033[0m'
log() { printf "%s\n" "${CYAN}[install]${RESET} $*"; }
warn() { printf "%s\n" "${YELLOW}[install]${RESET} $*" >&2; }
err()  { printf "%s\n" "${RED}[install]${RESET} $*" >&2; exit 1; }

# --- Locate the bundle directory ---------------------------------------------

BUNDLE_DIR="$(cd "$(dirname "$0")" && pwd)"
cd "$BUNDLE_DIR"

for f in docker-compose.yml .env.example caddy/Caddyfile; do
  [ -f "$f" ] || err "missing $f in $BUNDLE_DIR - run this from the extracted install bundle."
done

# --- Pre-flight ------------------------------------------------------------

command -v docker >/dev/null 2>&1 || err "docker is not installed or not in PATH"
docker compose version >/dev/null 2>&1 || err "the 'docker compose' plugin is required (got 'docker-compose'? install the v2 plugin)"

if ! command -v openssl >/dev/null 2>&1; then
  warn "openssl not found — Ed25519 keypair generation will be skipped, dev keys will be auto-generated by the collector on first boot."
  HAVE_OPENSSL=0
else
  HAVE_OPENSSL=1
fi

# --- Secret generators -----------------------------------------------------

# 32 random bytes, urlsafe-base64, WITH padding — Fernet requires exactly 44 chars.
gen_fernet_key() {
  python3 -c 'import secrets, base64; print(base64.urlsafe_b64encode(secrets.token_bytes(32)).decode())' 2>/dev/null \
  || { RAW="$(head -c 32 /dev/urandom | base64 | tr '+/' '-_' | tr -d '\n')"; printf '%s' "${RAW}$(printf '%0.s=' $(seq 1 $(( (4 - ${#RAW} % 4) % 4 ))))"; echo; }
}

# Generic high-entropy password / token.
gen_random() {
  python3 -c 'import secrets; print(secrets.token_urlsafe(32))' 2>/dev/null \
  || head -c 32 /dev/urandom | base64 | tr -d '=\n+/' | head -c 43
}

# Ed25519 keypair: PEM private + raw urlsafe-base64 public.
gen_ed25519_pair() {
  if [ "$HAVE_OPENSSL" -ne 1 ]; then
    return 1
  fi
  local tmp_priv tmp_pub
  tmp_priv="$(mktemp)"
  tmp_pub="$(mktemp)"
  openssl genpkey -algorithm ed25519 -out "$tmp_priv" 2>/dev/null
  openssl pkey -in "$tmp_priv" -pubout -outform DER 2>/dev/null \
    | tail -c 32 \
    | base64 \
    | tr '+/' '-_' \
    | tr -d '=\n' \
    > "$tmp_pub"
  PRIVKEY_PEM=$(cat "$tmp_priv")
  PUBKEY_B64=$(cat "$tmp_pub")
  rm -f "$tmp_priv" "$tmp_pub"
}

# --- .env generation -------------------------------------------------------

ENV_FILE="${BUNDLE_DIR}/.env"

if [ -f "$ENV_FILE" ]; then
  log "existing .env found at $ENV_FILE — merging in any missing secrets only."
else
  log "no .env yet — copying .env.example as the starting template."
  cp .env.example "$ENV_FILE"
fi

# Fill in any blank PINGIT_* secret. The bash glue is intentionally
# basic so the user can audit it before piping through `bash`.
fill_if_blank() {
  local key=$1
  local val=$2
  if grep -qE "^${key}=$" "$ENV_FILE"; then
    # The key exists with empty value — fill it.
    # Use a temp file to keep this portable across BSD/GNU sed.
    awk -v k="$key" -v v="$val" '
      $0 ~ "^"k"=" && $0 == k"=" { print k"="v; next }
      { print }
    ' "$ENV_FILE" > "$ENV_FILE.tmp" && mv "$ENV_FILE.tmp" "$ENV_FILE"
    log "  set $key (was blank)"
  fi
}

# Always set if blank, never overwrite.
fill_if_blank PINGIT_SESSION_SECRET "$(gen_random)"
fill_if_blank PINGIT_COOKIE_SIGNING_KEY "$(gen_random)"
fill_if_blank PINGIT_SECRETS_ENCRYPTION_KEY "$(gen_fernet_key)"

# Ed25519 keypair via openssl. We can't easily inline a multi-line PEM
# into the .env via fill_if_blank, so handle it here.
if grep -qE "^PINGIT_AGENT_SIGNING_PRIVKEY_PEM=$" "$ENV_FILE"; then
  if gen_ed25519_pair; then
    # Replace the PEM and PUB lines together.
    awk -v pem="$PRIVKEY_PEM" -v pub="$PUBKEY_B64" '
      $0 == "PINGIT_AGENT_SIGNING_PRIVKEY_PEM=" {
        # Encode newlines as \n so the .env stays single-line.
        gsub("\n", "\\n", pem)
        print "PINGIT_AGENT_SIGNING_PRIVKEY_PEM=" pem
        next
      }
      $0 == "PINGIT_AGENT_SIGNING_PUBKEY_B64=" {
        print "PINGIT_AGENT_SIGNING_PUBKEY_B64=" pub
        next
      }
      { print }
    ' "$ENV_FILE" > "$ENV_FILE.tmp" && mv "$ENV_FILE.tmp" "$ENV_FILE"
    log "  set PINGIT_AGENT_SIGNING_PRIVKEY_PEM + PINGIT_AGENT_SIGNING_PUBKEY_B64"
  else
    warn "skipped Ed25519 generation (no openssl); collector will lazily generate dev keys on first boot."
  fi
fi

# Set DB password if still on the dev placeholder.
if grep -qE "^POSTGRES_PASSWORD=changeme-dev-only" "$ENV_FILE"; then
  NEW_PW="$(gen_random)"
  awk -v v="$NEW_PW" '$0 ~ /^POSTGRES_PASSWORD=changeme-dev-only/ { print "POSTGRES_PASSWORD=" v; next } { print }' \
    "$ENV_FILE" > "$ENV_FILE.tmp" && mv "$ENV_FILE.tmp" "$ENV_FILE"
  log "  rotated POSTGRES_PASSWORD off the dev placeholder"
fi

chmod 0600 "$ENV_FILE"

# --- Compose up ------------------------------------------------------------

log "validating compose configuration..."
docker compose config -q

PINNED="$(grep -E '^PINGIT_VERSION=' "$ENV_FILE" | cut -d= -f2)"
log "pulling PingIt ${PINNED} images and starting the stack..."
docker compose pull
docker compose up -d

# --- Print final state -----------------------------------------------------

PORT="$(grep -E '^PINGIT_HTTPS_PORT=' "$ENV_FILE" | cut -d= -f2 || true)"
PORT="${PORT:-8443}"

cat <<EOF

${GREEN}PingIt is starting.${RESET}

  Open in a browser:    https://<this-host>:${PORT}/
                        (https://localhost:${PORT}/ on this machine)

  The certificate is issued by the bundled Caddy's own CA, so the browser warns
  once. See "TLS" in the README to use your own hostname and a real certificate.

${YELLOW}There is no default account.${RESET} The first page you see is the first-run
setup: enter the one-time setup token, then choose the admin email and password.
Read the token from the web container's log:
    docker compose logs web | grep 'SETUP TOKEN'
(allow ~30 seconds after start for the first boot). The setup page is only
available until the first admin exists.

Common follow-ups:
  docker compose ps                 # container health
  docker compose logs -f web        # tail the API logs
  docker compose exec web pingit admin reset --email you@example.com
                                    # break-glass: create/reset a local admin

EOF
